type Spec = {
  id: string;
  createdAt: string;
  brandId: BrandId;
  source: DetectionSource;
  campaignId?: string;
  domain: string;
  path?: string;
  extraUrls?: string[];
  title: string;
  faviconHue: number;
  htmlKit?: string;
  wallets?: string[];
  whois: WhoisStub;
  pageExcerpt: string;
  visualNotes: string;
  visualSimilarity: number;
  goldenLabel: Decision;
};

function specToDetection(spec: Spec): Detection {
  const path = spec.path ?? "/";
  const primaryUrl = `https://${spec.domain}${path === "/" ? "" : path}`;
  return {
    id: spec.id,
    createdAt: spec.createdAt,
    brandId: spec.brandId,
    source: spec.source,
    campaignId: spec.campaignId,
    goldenLabel: spec.goldenLabel,
    suspicious: {
      domain: spec.domain,
      urls: [primaryUrl, ...(spec.extraUrls ?? [])],
      title: spec.title,
      faviconHue: spec.faviconHue,
      htmlKit: spec.htmlKit,
      wallets: spec.wallets ?? [],
      whois: spec.whois,
      pageExcerpt: spec.pageExcerpt,
      visualNotes: spec.visualNotes,
      visualSimilarity: spec.visualSimilarity,
    },
  };
}

